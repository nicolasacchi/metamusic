func abcDoc(header string, body ...string) []byte {
	return []byte("X:1\nT:t\n" + header + "\n" + strings.Join(body, "\n") + "\n")
}

func bars(n int) string { return strings.TrimSuffix(strings.Repeat("CDEF|", n), "|") + "|]" }

func near(a, b float64) bool { return math.Abs(a-b) < 1e-9 }

func TestParseScore(t *testing.T) {
	rows := []struct {
		name  string
		abc   []byte
		spb   float64
		total float64
		meter string
		bars  int
	}{
		{"4/4 q120", abcDoc("M:4/4\nL:1/8\nQ:1/4=120\nK:C", bars(8)), 2.0, 16, "4/4", 8},
		{"6/8 q80", abcDoc("M:6/8\nL:1/8\nQ:3/8=80\nK:C", bars(4)), 1.5, 6, "6/8", 4},
		{"3/4 q90", abcDoc("M:3/4\nQ:1/4=90\nK:C", bars(3)), 2.0, 6, "3/4", 3},
		{"M:C", abcDoc("M:C\nQ:1/4=120\nK:C", bars(2)), 2.0, 4, "4/4", 2},
		{"M:C|", abcDoc("M:C|\nQ:1/2=60\nK:C", bars(2)), 2.0, 4, "2/2", 2},
		{"default meter", abcDoc("Q:1/4=120\nK:C", bars(2)), 2.0, 4, "4/4", 2},
		{"quoted tempo text", abcDoc("M:4/4\nQ:\"Allegro\" 1/4=120\nK:C", bars(2)), 2.0, 4, "4/4", 2},
		{"chord text barline ignored", abcDoc("M:4/4\nQ:1/4=120\nK:C", `"A|B"C D E F | "G"C D E F |]`), 2.0, 4, "4/4", 2},
		{"trailing partial bar", abcDoc("M:4/4\nQ:1/4=120\nK:C", `CDEF|CDEF|CD`), 2.0, 6, "4/4", 3},
		{"decorations skipped", abcDoc("M:4/4\nQ:1/4=120\nK:C", `!fermata!C D E F|+trill+CDEF|]`), 2.0, 4, "4/4", 2},
		{"directive and comments ignored", abcDoc("M:4/4\nQ:1/4=120\nK:C", "%%MIDI program 1\n% generated by tool\n"+bars(2)), 2.0, 4, "4/4", 2},
	}
	for _, r := range rows {
		t.Run(r.name, func(t *testing.T) {
			sc, err := ParseScore(r.abc)
			if err != nil {
				t.Fatal(err)
			}
			if !near(sc.SecondsPerBar, r.spb) {
				t.Fatalf("spb = %v want %v", sc.SecondsPerBar, r.spb)
			}
			if sc.Bars != r.bars || sc.Meter != r.meter {
				t.Fatalf("bars=%d meter=%s", sc.Bars, sc.Meter)
			}
			if !near(float64(sc.Bars)*sc.SecondsPerBar, r.total) {
				t.Fatalf("total = %v", float64(sc.Bars)*sc.SecondsPerBar)
			}
		})
	}
}

func TestParseScore_Untimed(t *testing.T) {
	rows := []struct {
		name string
		abc  []byte
	}{
		{"inline Q", abcDoc("M:4/4\nQ:1/4=120\nK:C", "CDEF|[Q:1/4=100]CDEF|]")},
		{"inline M", abcDoc("M:4/4\nQ:1/4=120\nK:C", "CDEF|[M:3/4]CDE|]")},
		{"bare Q", abcDoc("M:4/4\nQ:120\nK:C", bars(2))},
		{"no Q", abcDoc("M:4/4\nK:C", bars(2))},
		{"repeat start", abcDoc("M:4/4\nQ:1/4=120\nK:C", "|:CDEF|CDEF:|")},
		{"repeat end", abcDoc("M:4/4\nQ:1/4=120\nK:C", "CDEF|CDEF:|")},
		{"double colon", abcDoc("M:4/4\nQ:1/4=120\nK:C", "CDEF::CDEF|")},
		{"volta 1", abcDoc("M:4/4\nQ:1/4=120\nK:C", "CDEF|[1 CDEF|]")},
		{"volta 2", abcDoc("M:4/4\nQ:1/4=120\nK:C", "CDEF|[2 CDEF|]")},
		{"volta pipe", abcDoc("M:4/4\nQ:1/4=120\nK:C", "CDEF|1 CDEF|]")},
		{"volta pipe 2", abcDoc("M:4/4\nQ:1/4=120\nK:C", "CDEF|2 CDEF|]")},
		{"mid-tune Q field line", abcDoc("M:4/4\nQ:1/4=120\nK:C", "CDEF|\nQ:1/4=90\nCDEF|]")},
	}
	for _, r := range rows {
		t.Run(r.name, func(t *testing.T) {
			sc, err := ParseScore(r.abc)
			if err != nil {
				t.Fatal(err)
			}
			if sc.SecondsPerBar != 0 {
				t.Fatalf("spb = %v want 0", sc.SecondsPerBar)
			}
		})
	}
}

func TestParseScore_FinalBarlineNotARepeat(t *testing.T) {
	sc, err := ParseScore(abcDoc("M:4/4\nQ:1/4=120\nK:C", "CDEF|CDEF|]"))
	if err != nil || sc.SecondsPerBar != 2 || sc.Bars != 2 {
		t.Fatalf("%+v %v", sc, err)
	}
}

const hdr = "M:4/4\nL:1/8\nQ:1/4=120\n"

func TestParseScore_Interleaved(t *testing.T) {
	abc := abcDoc(hdr+"V:1\nV:2\nK:C",
		"% Verse 1", "V:1", "CDEF|CDEF|", "V:2", "CDEF|CDEF|",
		"% Chorus", "V:1", "CDEF|CDEF|CDEF|", "V:2", "CDEF|CDEF|CDEF|",
		"% Outro", "V:1", "CDEF|]", "V:2", "CDEF|]")
	sc, err := ParseScore(abc)
	if err != nil {
		t.Fatal(err)
	}
	want := []ScoreSection{
		{Kind: "verse", Label: "verse", Raw: "Verse 1", StartBar: 0, Bars: 2},
		{Kind: "chorus", Label: "chorus", Raw: "Chorus", StartBar: 2, Bars: 3},
		{Kind: "outro", Label: "outro", Raw: "Outro", StartBar: 5, Bars: 1},
	}
	if len(sc.Sections) != 3 {
		t.Fatalf("%+v", sc.Sections)
	}
	for i, w := range want {
		g := sc.Sections[i]
		if g.Kind != w.Kind || g.StartBar != w.StartBar || g.Bars != w.Bars {
			t.Errorf("section %d = %+v want %+v", i, g, w)
		}
	}
	if sc.Bars != 6 || sc.SecondsPerBar != 2 {
		t.Fatalf("bars=%d spb=%v", sc.Bars, sc.SecondsPerBar)
	}
}

func perVoice(v2labels ...string) []byte {
	lines := []string{"V:1", "% Verse", "CDEF|CDEF|", "% Chorus", "CDEF|CDEF|]", "V:2"}
	for _, l := range v2labels {
		lines = append(lines, "% "+l, "CDEF|CDEF|")
	}
	return abcDoc(hdr+"V:1\nV:2\nK:C", lines...)
}

func TestParseScore_PerVoice(t *testing.T) {
	sc, err := ParseScore(perVoice("Verse", "Chorus"))
	if err != nil {
		t.Fatal(err)
	}
	if len(sc.Sections) != 2 || sc.Sections[0].Bars != 2 || sc.Sections[1].StartBar != 2 || sc.Sections[1].Bars != 2 {
		t.Fatalf("%+v", sc.Sections)
	}
	if len(sc.Warnings) != 0 || sc.Bars != 4 {
		t.Fatalf("warnings=%v bars=%d", sc.Warnings, sc.Bars)
	}
	sc2, err := ParseScore(perVoice("Verse", "Bridge", "Chorus"))
	if err != nil {
		t.Fatal(err)
	}
	if len(sc2.Sections) != 2 || sc2.SecondsPerBar != 2 {
		t.Fatalf("%+v", sc2)
	}
	if diff := cmp.Diff([]string{"voice_sections_differ"}, sc2.Warnings); diff != "" {
		t.Fatal(diff)
	}
}

func TestAlignSections(t *testing.T) {
	lyr := []Section{{Kind: "verse"}, {Kind: "chorus"}, {Kind: "outro"}}
	sc := Score{SecondsPerBar: 2, Sections: []ScoreSection{
		{Kind: "verse", StartBar: 0, Bars: 2}, {Kind: "chorus", StartBar: 2, Bars: 2}, {Kind: "outro", StartBar: 4, Bars: 2},
	}}
	times, ok := AlignSections(lyr, sc)
	if !ok || cmp.Diff([][2]float64{{0, 4}, {4, 8}, {8, 12}}, times) != "" {
		t.Fatalf("%v %v", times, ok)
	}
	if _, ok := AlignSections(lyr[:2], sc); ok {
		t.Fatal("count mismatch must fail")
	}
	bad := []Section{{Kind: "verse"}, {Kind: "bridge"}, {Kind: "outro"}}
	if tm, ok := AlignSections(bad, sc); ok || tm != nil {
		t.Fatal("kind mismatch must fail")
	}
	sc.SecondsPerBar = 0
	if _, ok := AlignSections(lyr, sc); ok {
		t.Fatal("untimed must fail")
	}
}
