// The T1 fixture (C216.2) is SQL-only on top of FixtureL3, written through the library write path: the Takes the transform
// lanes need as inputs and the real-data shapes L3-X2 found missing from fixtures. No audio exists here; a lane that needs
// audio generates it at test time (dsptest, written to t.TempDir(); nothing audio is ever committed). Every text is synthetic.
//
// Labels of T1Info.Tx:
//
//	A      lossless Take, lyrics L, style "reggae, 92 bpm" (bpm_declared 92), feature row with a declared tempo basis
//	B      lossless Take, the SAME lyrics, style "eurodance, 128 bpm", measured tempo 128 (confidence 0.8, not octave ambiguous)
//	I      instrumental Take (empty lyrics), WS whitespace-only lyrics (both for lyrics_of)
//	S      Take with a score.abc and an aligned scores row (a plan bar grid with seconds_per_bar)
//	NF     lossless Take with no take_features row (a feature sweep has not run, or it was ingested seconds ago)
//	OCT    lossless Take whose feature row has bpm_octave set (measured 64 against requested 128)
//	MONO   near-mono stereo Take, WIDE a wide one, OOP an out-of-phase one (rows only; the audio is generated by dsptest)
//	P1..P3 a multi-part import: three lossy MP3 references syn_t1_p1..p3 (p1 the group root, p2 and p3 inferred siblings)
//
// The fixture also relies on what FixtureL3 holds and L3-X2 found in real data: draft-only Songs (d1-d4, u2), a reference FLAC
// (TrackRefFlac), a lossy reference (TrackLossy), Takes with measured features (T1-T8) and one without any Ears row (u1).

const (
	// T1Lyrics are the lyrics of A and B: equal, so lyrics_of finds each from the other.
	T1Lyrics = "[Verse 1]\nsynthetic transform line\n[Chorus]\nsynthetic transform hook"
	// T1ScoreLyrics have the three sections of the aligned ABC of S.
	T1ScoreLyrics = "[Verse 1]\nsynthetic score line\n[Chorus]\nsynthetic score hook\n[Outro]\nsynthetic score fade"
	// t1Space is the id range of the T1 rows (0xd4xxxx is free of every other fixture).
	t1Space = 0xd40000
)

// T1Info is the T1 world: everything FixtureL3 holds plus the Takes above.
type T1Info struct {
	L3Info
	// Tx maps the labels above to take ids.
	Tx map[string]string
	// Songs of the multi-part import (each lossy reference is a Take; their Songs are made by the Reconciler).
	Parts []string
}

func t1ID(n int) string { return fmt.Sprintf("01900000-0000-7000-8000-%012x", t1Space+n) }

type t1Take struct {
	label, style, lyrics, abc string
	dur                       float64
	lufs                      float64
	age                       time.Duration
	tempo                     float64 // measured tempo of an Ears analysis; 0 = none
	feature                   string  // "", "declared", "octave": the take_features row to write
}

var t1Takes = []t1Take{
	{label: "A", style: "reggae, 92 bpm", lyrics: T1Lyrics, dur: 20, lufs: -14, age: 5 * time.Hour, feature: "declared"},
	{label: "B", style: "eurodance, 128 bpm", lyrics: T1Lyrics, dur: 20, lufs: -12.5, age: 5*time.Hour + time.Minute, tempo: 128},
	{label: "I", style: "ambient, pad, 70 bpm", lyrics: "", dur: 20, lufs: -20, age: 5*time.Hour + 2*time.Minute},
	{label: "WS", style: "ambient, drone, 60 bpm", lyrics: "  \n \t\n", dur: 20, lufs: -21, age: 5*time.Hour + 3*time.Minute},
	{label: "S", style: "orchestral, 120 bpm", lyrics: T1ScoreLyrics, abc: alignedABC, dur: 16, lufs: -17, age: 5*time.Hour + 4*time.Minute},
	{label: "NF", style: "pop, 100 bpm", lyrics: T1Lyrics + "\n[Outro]\nsynthetic no features", dur: 20, lufs: -14, age: 5*time.Hour + 5*time.Minute},
	{label: "OCT", style: "dance, 128 bpm", lyrics: T1Lyrics + "\n[Bridge]\nsynthetic octave", dur: 20, lufs: -13, age: 5*time.Hour + 6*time.Minute, tempo: 64, feature: "octave"},
	{label: "MONO", style: "folk, 90 bpm", lyrics: "[Verse 1]\nsynthetic mono line", dur: 12, lufs: -18, age: 5*time.Hour + 7*time.Minute},
	{label: "WIDE", style: "ambient, wide, 80 bpm", lyrics: "[Verse 1]\nsynthetic wide line", dur: 12, lufs: -18, age: 5*time.Hour + 8*time.Minute},
	{label: "OOP", style: "ambient, phase, 80 bpm", lyrics: "[Verse 1]\nsynthetic phase line", dur: 12, lufs: -18, age: 5*time.Hour + 9*time.Minute},
}

type t1Builder struct {
	tb  testing.TB
	st  *store.Store
	now time.Time
	out T1Info
	n   int
}

func (b *t1Builder) id() string { b.n++; return t1ID(b.n) }

// takes inserts the lossless Takes through the library write path.
func (b *t1Builder) takes() {
	ctx := context.Background()
	svc := library.New(b.st, nil, func() time.Time { return b.now })
	svc.UseIDFunc(b.id)
	for i, tk := range t1Takes {
		id := b.id()
		b.out.Tx[tk.label] = id
		tx := begin(b.tb, b.st)
		title := "Synthetic Take X" + tk.label
		slug := yue2.Slug(title)
		h := sha(fmt.Appendf(nil, "t1-take/%s", tk.label))
		series := make([]float64, int(tk.dur))
		for j := range series {
			series[j] = tk.lufs
		}
		nt := library.NewTake{
			ID: id, Title: title, Slug: slug, PrincipalID: "cli", RecordedAt: b.now.Add(-tk.age),
			DurationS: tk.dur, SampleRate: 48000, BitsPerSample: 24, Channels: 2, TotalSamples: int64(tk.dur * 48000),
			MasterPath: "audio/masters/" + slug + "__" + h[:8] + ".flac", MasterSHA256: h, MasterBytes: 64,
			SourceSHA256: sha([]byte("t1-src/" + tk.label)), FramesSHA256: sha([]byte("t1-frames/" + tk.label)), AudioMD5: h[:32],
			Loudness: analysis.Loudness{IntegratedLUFS: tk.lufs, LRA: 5, LRALowLUFS: tk.lufs - 4, LRAHighLUFS: tk.lufs + 1.5, TruePeakDBTP: -3, SamplePeakDBFS: -3.3,
				ShortTermMaxLUFS: tk.lufs + 1, ShortTerm1Hz: series},
			Spectrum:    analysis.Spectrum{BandwidthHz: bptrInt(16000), RefDB: -40, ThresholdDB: -110, Frames: 30},
			ToolVersion: "ffmpeg n9.0.1", ReplayGainDB: -18 - tk.lufs,
			Renditions: []library.NewRendition{{Kind: "peaks", SHA256: sha([]byte("t1-peaks/" + tk.label)), Bytes: 32, Path: "derived/t1/" + h[:16] + ".peaks.json", Params: map[string]any{"format": analysis.PeaksFormat}}},
		}
		if tk.abc != "" {
			nt.ScoreABC = []byte(tk.abc)
		}
		p := mustParse(b.tb, reqJSON("t1_"+tk.label, tk.style, tk.lyrics, int64(8300+i)))
		rid, _, err := svc.InsertRecipe(ctx, tx, p, "import")
		check(b.tb, err)
		nt.RecipeID, nt.ImportRule = rid, "slug"
		check(b.tb, svc.InsertTake(ctx, tx, nt))
		check(b.tb, tx.Commit())
	}
}

// analyses and features write the Ears tempo analysis of B and OCT and the take_features rows of A (declared basis) and OCT
// (bpm_octave set); NF has no row at all, and neither has any other T1 take.
func (b *t1Builder) analyses() {
	tx := begin(b.tb, b.st)
	at := store.FormatTime(b.now.Add(-4 * time.Hour))
	digest := Sha("t1-literal")
	for _, tk := range t1Takes {
		id := b.out.Tx[tk.label]
		if tk.tempo > 0 {
			if _, err := tx.ExecContext(context.Background(), `INSERT INTO analyses(track_id,analyzer,version,tier,metrics_json,created_at) VALUES(?,'tempo','mm-tempo/1 ffmpeg n9.0.1','A',?,?)`,
				id, fmt.Sprintf(`{"bpm":%.1f,"confidence":0.8,"octave_ambiguous":%t,"analyzed_s":%.0f}`, tk.tempo, tk.feature == "octave", tk.dur), at); err != nil {
				b.tb.Fatal(err)
			}
		}
		var q string
		var args []any
		switch tk.feature {
		case "declared":
			q = `INSERT INTO take_features(track_id,bpm_x100,bpm_basis,bpm_requested_x100,bpm_octave,energy_x10000,energy_basis,duration_s,digest,feature_def,computed_at)
				VALUES(?,9200,'declared',9200,0,5000,'predicted',?,?,'mm-features/1',?)`
			args = []any{id, tk.dur, digest, at}
		case "octave":
			q = `INSERT INTO take_features(track_id,bpm_x100,bpm_basis,bpm_requested_x100,bpm_measured_x100,bpm_octave,energy_x10000,energy_basis,duration_s,digest,feature_def,computed_at)
				VALUES(?,12800,'declared',12800,6400,1,7000,'predicted',?,?,'mm-features/1',?)`
			args = []any{id, tk.dur, digest, at}
		default:
			continue
		}
		if _, err := tx.ExecContext(context.Background(), q, args...); err != nil {
			b.tb.Fatal(err)
		}
	}
	check(b.tb, tx.Commit())
}

// multipart inserts the three lossy MP3 references syn_t1_p1..p3 of one imported song: p1 is the group root, p2 and p3 are
// generation-1 children with inferred_sibling mutations of rule reference_group (the shape M2c's importer writes).
func (b *t1Builder) multipart() {
	ctx := context.Background()
	svc := library.New(b.st, nil, func() time.Time { return b.now })
	svc.UseIDFunc(b.id)
	var root string
	for i := 1; i <= 3; i++ {
		title := fmt.Sprintf("Synthetic Trio X p%d", i)
		slug := yue2.Slug(title)
		id := b.id()
		b.out.Parts = append(b.out.Parts, id)
		master := []byte(fmt.Sprintf("t1-lossy-master-%d", i))
		msha := sha(master)
		tx := begin(b.tb, b.st)
		rid, _, err := svc.InsertReferenceRecipe(ctx, tx, library.NewReferenceRecipe{Title: title, Slug: slug, AudioKey: fmt.Sprintf("mp3:t1-trio-p%d", i)})
		check(b.tb, err)
		nt := library.NewTake{
			ID: id, Title: title, Slug: slug, RecipeID: rid, Reference: true, Lossy: true, ImportRule: library.RuleReference, PrincipalID: "cli",
			DurationS: 8, SampleRate: 44100, BitsPerSample: 16, Channels: 2, TotalSamples: 8 * 44100,
			MasterPath: fmt.Sprintf("audio/masters/%s__0__20261001-1200.mp3", slug), MasterSHA256: msha, MasterBytes: int64(len(master)),
			SourceSHA256: msha, FramesSHA256: msha, AudioMD5: "00000000000000000000000000000000", ImportRunID: RunID, RecordedAt: b.now.Add(-time.Duration(20-i) * time.Hour),
			Loudness:    analysis.Loudness{IntegratedLUFS: -14, LRA: 4, LRALowLUFS: -18, LRAHighLUFS: -12, TruePeakDBTP: -1.0, SamplePeakDBFS: -1.2, ShortTermMaxLUFS: -12, ShortTerm1Hz: []float64{-14, -14}},
			Spectrum:    analysis.Spectrum{BandwidthHz: bptrInt(16000), RefDB: -40, ThresholdDB: -110, Frames: 30},
			ToolVersion: "ffmpeg n9.0.1", ReplayGainDB: -4,
			Renditions: []library.NewRendition{{Kind: "peaks", SHA256: sha([]byte(fmt.Sprintf("t1-lossy-peaks-%d", i))), Bytes: 32, Path: fmt.Sprintf("derived/t1/lossy%d.peaks.json", i), Params: map[string]any{"format": analysis.PeaksFormat}}},
		}
		if i == 1 {
			root = id
		} else {
			nt.ParentTrackID, nt.RootTrackID, nt.Generation = root, root, 1
			nt.Mutation = &library.NewMutation{Operator: "inferred_sibling", Inferred: true, Rule: "reference_group"}
		}
		check(b.tb, svc.InsertTake(ctx, tx, nt))
		check(b.tb, tx.Commit())
	}
}

func newT1Builder(tb testing.TB, st *store.Store, now time.Time, base L3Info) *t1Builder {
	tb.Helper()
	return &t1Builder{tb: tb, st: st, now: now, out: T1Info{L3Info: base, Tx: map[string]string{}}}
}

func (b *t1Builder) world() T1Info {
	b.takes()
	b.analyses()
	b.multipart()
	for _, tk := range t1Takes {
		b.out.Tracks = append(b.out.Tracks, b.out.Tx[tk.label])
	}
	b.out.Tracks = append(b.out.Tracks, b.out.Parts...)
	return b.out
}

// FixtureT1 is FixtureL3 plus the T1 world described at the top of this file. The queue is not drained: a Settle derives the
// Songs, Picks and Sounds of the new Takes. It needs schema 11 or later and writes no transform row.
func FixtureT1(tb testing.TB, st *store.Store, now time.Time) T1Info {
	tb.Helper()
	return newT1Builder(tb, st, now, FixtureL3(tb, st, now)).world()
}

// ApplyT1 adds the T1 world to a library that already holds FixtureL3's rows (servertest uses it).
func ApplyT1(tb testing.TB, st *store.Store, now time.Time) T1Info {
	tb.Helper()
	b := newT1Builder(tb, st, now, L3Info{})
	return b.world()
}
