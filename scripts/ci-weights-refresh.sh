#!/usr/bin/env bash
# Usage: scripts/ci-weights-refresh.sh write <timings> [shards]   rewrite scripts/ci-shard-weights.txt and ci-heavy-tests.txt
#        scripts/ci-weights-refresh.sh check <timings> [min-seconds]   fail when a package slower than min-seconds (15)
#                                                                  has no weight entry; warn about weights off by more than 2x
#        scripts/ci-weights-refresh.sh table <timings>             print "<seconds> <pkg>" and "<seconds> <pkg> <test>"
# <timings> is a directory of `go test -json` streams (*.jsonl; the CI go jobs upload them as the gotimings-N artifacts,
# written by scripts/ci-go-test.sh when MM_GO_TIMINGS is set), or a GitHub Actions run id, whose gotimings-* artifacts
# are downloaded with gh. To refresh after a change to the suite:
#   scripts/ci-weights-refresh.sh write <run-id-of-a-green-main-run>      # then commit the two files
# Package weight = the summed wall seconds of its `go test` runs in that CI run (all parts of a split package added up).
# Every package of 1 s or more is listed (so a contention spike over the 15 s check limit does not flake the gate).
# A package heavier than a third of a shard's even share is split K ways (K <= 4); the top-level tests of a split package
# taking >= 8 s are pinned to parts by longest-first packing (ci-heavy-tests.txt), the rest fall back to the name hash.
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
cd "$root"
W=${MM_WEIGHTS_FILE:-$root/scripts/ci-shard-weights.txt}
H=${MM_HEAVY_FILE:-$root/scripts/ci-heavy-tests.txt}

cmd=${1:?write|check|table}
src=${2:?timings dir or run id}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

if [[ "$src" =~ ^[0-9]+$ ]]; then
  gh run download "$src" --pattern 'gotimings-*' --dir "$tmp/dl" >/dev/null
  src=$tmp/dl
fi
[ -d "$src" ] || { echo "ci-weights-refresh: $src is not a directory" >&2; exit 2; }
find "$src" -name '*.jsonl' | grep -q . || { echo "ci-weights-refresh: no *.jsonl under $src" >&2; exit 2; }

mod=$(go list -m)
# pkg rows "P <pkg> <seconds>" and test rows "T <pkg> <test> <seconds>", package paths ./-relative
find "$src" -name '*.jsonl' -print0 | xargs -0 cat | jq -rR --arg mod "$mod" '
  fromjson? | select(.Package != null and (.Action == "pass" or .Action == "fail") and .Elapsed != null)
  | (.Package | sub("^" + $mod; ".")) as $p
  | if .Test == null then "P \($p) \(.Elapsed)" else "T \($p) \(.Test) \(.Elapsed)" end' >"$tmp/raw"

awk '$1 == "P" { t[$2] += $3 } END { for (p in t) printf "%.1f %s\n", t[p], p }' "$tmp/raw" | sort -k1,1nr -k2 >"$tmp/pkgs"
# top-level test weight = max(own elapsed, sum of its direct subtests): a parent of parallel subtests can report little
awk '$1 == "T" {
       n = split($3, a, "/")
       if (n == 1) own[$2 " " $3] = $4
       else if (n == 2) sub_[$2 " " a[1]] += $4
     }
     END { for (k in own) { v = own[k]; if (sub_[k] > v) v = sub_[k]; printf "%.1f %s\n", v, k }
           for (k in sub_) if (!(k in own)) printf "%.1f %s\n", sub_[k], k }' "$tmp/raw" | sort -k1,1nr >"$tmp/tests"

case "$cmd" in
  table)
    cat "$tmp/pkgs"; echo; cat "$tmp/tests" ;;
  check)
    min=${3:-15}
    bad=0
    while read -r sec pkg; do
      listed=$(awk -v p="$pkg" '$1 !~ /^#/ && $1 == p { print $2; exit }' "$W")
      if [ -z "$listed" ]; then
        if awk -v s="$sec" -v m="$min" 'BEGIN { exit !(s > m) }'; then
          echo "ci-weights-refresh: $pkg took ${sec}s in the run but has no entry in ${W#$root/}" >&2; bad=1
        fi
      elif awk -v s="$sec" -v w="$listed" 'BEGIN { exit !(w >= 30 && (s > 2 * w || s < w / 2)) }'; then
        echo "ci-weights-refresh: warning: $pkg weighs $listed but took ${sec}s (stale weight; run scripts/ci-weights-refresh.sh write <run>)" >&2
      fi
    done <"$tmp/pkgs"
    [ "$bad" = 0 ] && echo "ci-weights-refresh: every package slower than ${min}s has a weight entry"
    exit $bad ;;
  write)
    n=${3:-6}
    total=$(awk '{ s += $1 } END { printf "%.0f", s }' "$tmp/pkgs")
    {
      echo "# pkg  weight(wall seconds of the package in a CI run, summed over its parts)  [split K = also shard its top-level tests K ways]"
      echo "# Generated by scripts/ci-weights-refresh.sh from a CI run's go test -json timings ($(date -u +%Y-%m-%d), ${n} shards, ${total} s total)."
      echo "# Packages not listed weigh 3. The weights only balance the shards; coverage of every package and test is"
      echo "# structural (scripts/ci-go-test.sh --plan, asserted by scripts/ci-selftest.sh), so stale numbers cost time, never tests."
      echo "# scripts/ci-tiers-selftest.sh and the CI coverage job fail when a package slower than 15 s has no line here."
      awk -v n="$n" -v total="$total" '
        $1 >= 1 { w = int($1 + 0.5); k = 1; share = total / n
                  if (w > share / 3) { k = int(w / (share / 3) + 0.999); if (k > 4) k = 4 }
                  if (k > 1) printf "%s %d %d\n", $2, w, k; else printf "%s %d\n", $2, w }' "$tmp/pkgs"
    } >"$tmp/weights"
    {
      echo "# pkg  top-level test  seconds-in-a-CI-run  part"
      echo "# Tests of a package that scripts/ci-shard-weights.txt splits are spread over its K parts by a stable hash of the test"
      echo "# name, which can pile every slow test into one part. A test listed here goes to the given part (0-based, taken mod K)"
      echo "# instead. Generated by scripts/ci-weights-refresh.sh (longest test first onto the least loaded part; seconds are the"
      echo "# test's wall time, parallel subtests summed). A name that no longer exists is harmless; a new slow test falls back to the hash."
      awk -v wf="$tmp/weights" '
        BEGIN { while ((getline l < wf) > 0) { if (l ~ /^#/) continue; split(l, f, " "); if (f[3] > 1) { K[f[1]] = f[3]; W[f[1]] = f[2] } } }
        { pkg = $2; if (!(pkg in K)) next; t = $3; s = $1
          if (s < 8) { small[pkg] += s; next }
          cnt[pkg]++; ts[pkg, cnt[pkg]] = s; tn[pkg, cnt[pkg]] = t }
        END {
          for (pkg in K) {
            k = K[pkg]
            for (i = 0; i < k; i++) load[pkg, i] = small[pkg] / k
            # tests arrive sorted by seconds descending, so the pinned ones are placed longest first
            for (j = 1; j <= cnt[pkg]; j++) {
              best = 0; for (i = 1; i < k; i++) if (load[pkg, i] < load[pkg, best]) best = i
              load[pkg, best] += ts[pkg, j]
              printf "%s %s %d %d\n", pkg, tn[pkg, j], ts[pkg, j] + 0.5, best
            }
          }
        }' "$tmp/tests" | sort -k1,1 -k3,3nr
    } >"$tmp/heavy"
    cp "$tmp/weights" "$W"; cp "$tmp/heavy" "$H"
    echo "ci-weights-refresh: wrote ${W#$root/} ($(grep -vc '^#' "$W") packages) and ${H#$root/} ($(grep -vc '^#' "$H") pinned tests)" ;;
  *) echo "usage: $0 write|check|table <timings> ..." >&2; exit 2 ;;
esac
