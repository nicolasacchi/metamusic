#!/usr/bin/env bash
# Worker contract tests against the real yue2 (CPU torch), C83.4/C85. Same steps as
# .github/workflows/worker-contract.yml, which calls this script. Infra owns the file; the Worker lane
# (M3-P2) supplies the pytest target (worker/contract). No GPU, no weights, no secrets.
# YUE2_COMMIT (40 hex) comes from the environment or from the pin file worker/contract/YUE2_COMMIT.
#
# Usage: scripts/worker-contract.sh [yue2|acestep15] [--check]      (the ENGINE environment variable works too; default yue2)
# BEGIN E2-I1 engine argument: acestep15 runs worker/contract/test_acestep_contract.py against the pinned ACE-Step commit
# (ACESTEP_COMMIT from the environment or worker/contract/ACESTEP_COMMIT) on Python 3.11 (upstream's target; flash-attn and triton
# are cp311) with CPU torch. The inference-only requirement list is worker/contract/acestep-requirements.txt (PW2, generated by
# E2-P0a; ACE-Step is installed --no-deps because its published dependency set drags in gradio, tensorboard and lightning).
# ACE-Step code runs only here (CI) and in the image, never on a developer machine. --check validates the pins and the files
# and exits before any download (scripts/ci-tiers-selftest.sh runs it).
# END E2-I1
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
cd "$root"
engine=${ENGINE:-yue2}
check=0
for a in "$@"; do
  case "$a" in
    yue2 | acestep15) engine=$a ;;
    --check) check=1 ;;
    *) echo "worker-contract: unknown argument: $a (want yue2|acestep15 [--check])" >&2; exit 2 ;;
  esac
done
case "$engine" in
  yue2) pin_var=YUE2_COMMIT pin_file=worker/contract/YUE2_COMMIT pyver=3.12 target=contract/test_yue2_contract.py ;;
  acestep15) pin_var=ACESTEP_COMMIT pin_file=worker/contract/ACESTEP_COMMIT pyver=3.11 target=contract/test_acestep_contract.py ;;
  *) echo "worker-contract: unknown ENGINE: $engine" >&2; exit 2 ;;
esac
TORCH_VERSION=${TORCH_VERSION:-2.10.0}
commit=${!pin_var:-}
if [ -z "$commit" ] && [ -f "$pin_file" ]; then
  commit=$(tr -d '[:space:]' < "$pin_file")
fi
printf '%s' "$commit" | grep -Eq '^[0-9a-f]{40}$' || {
  echo "worker-contract: $pin_var must be a 40-hex commit (env or $pin_file)" >&2
  exit 2
}
[ -f "worker/$target" ] || { echo "worker-contract: worker/$target is missing" >&2; exit 2; }
if [ "$engine" = acestep15 ]; then
  reqs=worker/contract/acestep-requirements.txt
  [ -f "$reqs" ] || { echo "worker-contract: $reqs is missing (the inference-only requirement list, PW2)" >&2; exit 2; }
fi
if [ "$check" = 1 ]; then
  echo "worker-contract: $engine pins ok ($pin_var=$commit, python $pyver, torch $TORCH_VERSION)"
  exit 0
fi
venv=${WORKER_CONTRACT_VENV:-$root/worker/.venv-contract}
uv venv --python "$pyver" "$venv"
export VIRTUAL_ENV="$venv" PATH="$venv/bin:$PATH"
uv pip install "torch==${TORCH_VERSION}" --index-url https://download.pytorch.org/whl/cpu
if [ "$engine" = acestep15 ]; then
  uv pip install -r "$reqs"
  uv pip install --no-deps "ace-step @ git+https://github.com/ace-step/ACE-Step-1.5@${commit}"
else
  uv pip install "yue2-infer @ git+https://github.com/multimodal-art-projection/YuE@${commit}"
fi
uv pip install -e worker --no-deps
uv pip install --group worker/pyproject.toml:dev
cd worker
python -m pytest "$target"
